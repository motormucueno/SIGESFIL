import datetime
import sqlite3
def inserir_dados(tabela:str=None, dados:list=None):
    conn = sqlite3.connect('db.sqlite3')
    cursor = conn.cursor()
    for dado in dados:
        agora = datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S')
        cursor.execute(f'INSERT INTO {tabela} (nome, criado_em, actualizado_em) VALUES (?,?,?)', (dado,agora,agora))
        conn.commit()
    conn.close()
